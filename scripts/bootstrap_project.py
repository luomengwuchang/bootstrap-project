def project_title(project_dir: Path) -> str:
    name = project_dir.name.strip() or "新项目"
    return name.replace("_", " ").replace("-", " ")


# Stack markers -> .gitignore block key. Detection runs once at file-creation
# time; a brand-new empty directory matches nothing and falls back to the
# common block. Append stack-specific entries later as code is added.
STACK_MARKERS = [
    ("package.json", "node"),
    ("pyproject.toml", "python"), ("setup.py", "python"),
    ("requirements.txt", "python"), ("Pipfile", "python"),
    ("go.mod", "go"),
    ("Cargo.toml", "rust"),
    ("pom.xml", "java"), ("build.gradle", "java"), ("build.gradle.kts", "java"),
    ("composer.json", "php"),
    ("Gemfile", "ruby"),
    ("pubspec.yaml", "dart"),
]

IGNORE_BLOCKS = {
    "common": "# OS / editor\n.DS_Store\nThumbs.db\n.idea/\n.vscode/\n*.swp\n\n"
              "# Logs and runtime\n*.log\nlogs/\n*.pid\n*.tmp\n*.temp\n\n"
              "# Local config and secrets\n.env\n.env.*\n!.env.example\n*.pem\n*.key\n*.p12\n*.pfx\n",
    "node": "# Node\nnode_modules/\n# Review before ignoring semantic build directories:\n# dist/\n# build/\n.next/\n.vite/\ncoverage/\n",
    "python": "# Python\n__pycache__/\n*.py[cod]\n.pytest_cache/\n.mypy_cache/\n.ruff_cache/\n.venv/\nvenv/\n*.egg-info/\n",
    "go": "# Go\n*.exe\n*.exe~\n*.so\n*.dylib\n# Review before ignoring a semantic binary directory:\n# bin/\n",
    "rust": "# Rust\n/target/\n**/*.rs.bk\n# Cargo.lock: commit for apps/binaries, ignore for libraries\n",
    "java": "# Java (Maven/Gradle)\ntarget/\n*.class\n*.jar\n*.war\n.gradle/\n!gradle/wrapper/gradle-wrapper.jar\n# Review before ignoring semantic build or vendor directories:\n# build/\n# bin/\n# vendor/\n",
    "php": "# PHP\nvendor/\n",
    "ruby": "# Ruby\n/.bundle/\n/vendor/bundle/\n*.gem\n",
    "dart": "# Dart/Flutter\n.dart_tool/\n# Review before ignoring semantic build output:\n# build/\n",
    "dotnet": "# .NET\nbin/\nobj/\n*.user\n*.suo\n",
}


def detect_stacks(project_dir: Path) -> list[str]:
    found: list[str] = []
    for marker, stack in STACK_MARKERS:
        if (project_dir / marker).exists() and stack not in found:
            found.append(stack)
    if any(project_dir.glob("*.sln")) or any(project_dir.glob("*.csproj")):
        found.append("dotnet")
    return found


def build_gitignore(project_dir: Path) -> str:
    stacks = detect_stacks(project_dir)
    parts = [IGNORE_BLOCKS["common"]]
    if not stacks:
        parts.append("# No language stack detected yet — append your stack's ignores when code is added.\n")
    for stack in stacks:
        parts.append(IGNORE_BLOCKS[stack])
    return "\n".join(parts)


