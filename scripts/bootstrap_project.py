def parse_last_tidy(text: str) -> date | None:
    for line in text.splitlines():
        for label in ("最后整理", "Last reviewed"):
            if line.startswith(label):
                value = line[len(label):].strip().lstrip("：:").strip()
                try:
                    return date.fromisoformat(value)
                except ValueError:
                    return None
    return None


def parse_structure_tree(text: str) -> set[str]:
    """Top-level entry names from the first ```text block that contains tree
    lines. Blocks without any tree prefix (URLs, command output) are skipped;
    indented (nested) entries are ignored so only top-level names are compared."""
    names: set[str] = set()
    in_tree = False
    for line in text.splitlines():
        stripped = line.strip()
        if not in_tree:
            if stripped.startswith("```text"):
                in_tree = True
            continue
        if stripped.startswith("```"):
            if names:
                break
            in_tree = False
            continue
        for prefix in TREE_PREFIXES:
            if line.startswith(prefix):
                entry = line[len(prefix):].split("#", 1)[0].strip()
                names.add(entry.rstrip("/"))
                break
    return names


@dataclass
class CheckItem:
    code: str
    level: str
    path: str
    message: str


@dataclass
class CheckResult:
    target: str
    level: str
    checks: list[CheckItem] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    exit_code: int = 0
    dry_run: bool = False
    stale_days: int = STALE_DAYS
    placeholders: tuple[str, ...] = (PLACEHOLDER,)

    def add(self, code: str, level: str, path: str = "", message: str = "") -> None:
        self.checks.append(CheckItem(code, level, path, message))

    def as_dict(self) -> dict[str, object]:
        return {
            "operation": "check",
            "target": self.target,
            "mode": "check",
            "level": self.level,
            "stale_days": self.stale_days,
            "placeholders": list(self.placeholders),
            "created": [],
            "skipped": [],
            "conflicts": [],
            "git": "",
            "commit": "",
            "report": "",
            "checks": [
                {"code": item.code, "level": item.level, "path": item.path, "message": item.message}
                for item in self.checks
            ],
            "errors": self.errors,
            "exit_code": self.exit_code,
            "dry_run": self.dry_run,
        }


