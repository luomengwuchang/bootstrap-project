def blocking_levels(level: str) -> set[str]:
    """Check levels that make a run fail: warnings block only in strict mode."""
    return {"issue", "warning"} if level == "strict" else {"issue"}


def check_result(
    project_dir: Path, *, level: str = "standard", dry_run: bool = False,
    stale_days: int = STALE_DAYS, extra_placeholders: tuple[str, ...] = (),
) -> CheckResult:
    """Build a structured health result without creating or modifying files."""
    result = CheckResult(
        str(project_dir), level, dry_run=dry_run, stale_days=stale_days,
        placeholders=tuple(dict.fromkeys((PLACEHOLDER, *extra_placeholders))),
    )
    if stale_days < 0 or any(not value.strip() for value in result.placeholders):
        result.errors.append("stale_days must be non-negative and placeholders must not be blank")
        result.exit_code = 1
        return result
    if os.path.lexists(project_dir) and project_dir.is_symlink():
        result.errors.append("target is a symbolic link, not a regular directory")
        result.exit_code = 1
        return result
    try:
        project_dir = project_dir.resolve()
    except OSError as exc:
        result.errors.append(f"unable to resolve target: {exc}")
        result.exit_code = 1
        return result
    result.target = str(project_dir)
    if project_dir.is_symlink() or not project_dir.is_dir():
        result.errors.append("target is not a regular directory")
        result.exit_code = 1
        return result

    try:
        entries = list(project_dir.iterdir())
    except OSError as exc:
        result.errors.append(f"unable to inspect target directory: {exc}")
        result.exit_code = 1
        return result

    missing = [name for name in DOC_FILES if not os.path.lexists(project_dir / name)]
    conflicts = [
        name for name in DOC_FILES
        if os.path.lexists(project_dir / name)
        and not ((project_dir / name).is_file() and not (project_dir / name).is_symlink())
    ]
    if conflicts:
        for name in conflicts:
            result.add("path_conflict", "issue", name, "path is not a regular file")
    if missing:
        if set(missing) == {"PROJECT_CONTEXT.md", "PLANS.md"} and not conflicts:
            result.add("lite_layout", "info", "", "PROJECT_CONTEXT.md and PLANS.md absent - lite layout")
        else:
            for name in missing:
                result.add("missing_file", "issue", name, "required starter file is missing")

    document_text: dict[str, str] = {}
    for name in DOC_FILES:
        path = project_dir / name
        if not path.exists() or not path.is_file() or path.is_symlink():
            continue
        try:
            text = path.read_text(encoding="utf-8-sig")
        except UnicodeDecodeError as exc:
            result.add("invalid_encoding", "issue", name, f"file is not valid UTF-8: {exc}")
        except OSError as exc:
            result.add("unreadable_file", "issue", name, str(exc))
        else:
            # An empty .gitignore is valid; content checks apply to Markdown.
            if name != ".gitignore":
                document_text[name] = text

    for name, text in document_text.items():
        if not text.strip() and level in {"standard", "strict"}:
            result.add("empty_document", "issue", name, "document is empty or contains only whitespace")
            continue
        count = sum(text.count(value) for value in result.placeholders)
        if count and level in {"standard", "strict"}:
            result.add("placeholder", "issue", name, f"{count} unfilled placeholder(s)")

    context_text = document_text.get("PROJECT_CONTEXT.md")
    if context_text and context_text.strip() and level in {"standard", "strict"}:
        tidy = parse_last_tidy(context_text)
        if tidy is None:
            result.add("stale_context", "issue", "PROJECT_CONTEXT.md", "last-tidy date not found or unparseable")
        else:
            age = (date.today() - tidy).days
            if stale_days == 0:
                result.add("context_age", "info", "PROJECT_CONTEXT.md", f"last tidy was {age} days ago; age limit disabled")
            elif age > stale_days:
                result.add("stale_context", "issue", "PROJECT_CONTEXT.md", f"last tidy was {age} days ago")
            else:
                result.add("fresh_context", "info", "PROJECT_CONTEXT.md", f"last tidy was {age} days ago")

        tree_names = {n for n in parse_structure_tree(context_text) if not n.startswith(".")}
        if tree_names:
            actual = {p.name for p in entries if not p.name.startswith(".")}
            # Noise may be omitted from the docs, but a documented entry must
            # still be checked against the complete set of actual entries.
            added = sorted(actual - tree_names - NOISE_NAMES)
            gone = sorted(tree_names - actual)
            if added or gone:
                parts = []
                if added:
                    parts.append("on disk but not in tree: " + ", ".join(added[:8]) + ("..." if len(added) > 8 else ""))
                if gone:
                    parts.append("in tree but not on disk: " + ", ".join(gone[:8]) + ("..." if len(gone) > 8 else ""))
                result.add("structure_drift", "issue", "PROJECT_CONTEXT.md", "; ".join(parts))
            else:
                result.add("structure_match", "info", "PROJECT_CONTEXT.md", "tree matches top-level entries")
        elif level in {"standard", "strict"}:
            result.add("structure_missing", "warning", "PROJECT_CONTEXT.md", "no structure tree found")

    git_is_repository = False
    try:
        git_is_repository = has_git_repository(project_dir)
    except (OSError, RuntimeError) as exc:
        result.add("git_error", "issue", ".git", str(exc))
    else:
        if not git_is_repository:
            result.add("no_git", "issue", ".git", "Git repository is missing")
        elif level == "basic":
            result.add("git_ok", "info", ".git", "Git repository is present")
        else:
            try:
                head = read_git(project_dir, "rev-parse", "--verify", "HEAD")
            except OSError as exc:
                result.add("git_error", "issue", ".git", f"unable to run git: {exc}")
            else:
                if head.returncode == 0:
                    result.add("git_ok", "info", ".git", "repository has commits")
                elif level == "strict":
                    result.add("no_head", "issue", ".git", "repository has no commits yet")
                else:
                    result.add("no_head", "warning", ".git", "repository has no commits yet")

    if level == "strict":
        for name in ("PROJECT_CONTEXT.md", "PLANS.md"):
            if name in missing:
                result.add("missing_file", "issue", name, "strict mode requires complete documentation")
        if git_is_repository:
            try:
                status = read_git(project_dir, "status", "--porcelain")
            except OSError as exc:
                result.add("git_error", "issue", ".git", f"unable to read worktree status: {exc}")
            else:
                if status.returncode == 0 and status.stdout.strip():
                    result.add("dirty_worktree", "issue", ".git", "worktree has uncommitted changes")
                elif status.returncode != 0:
                    result.add("git_error", "issue", ".git", "unable to read worktree status")

    result.exit_code = 1 if result.errors or any(item.level in blocking_levels(level) for item in result.checks) else 0
    return result


def render_check(result: CheckResult) -> str:
    lines = [f"target: {result.target}", "mode: check"]
    for error in result.errors:
        lines.append(f"error: {error}")
    grouped: dict[str, list[CheckItem]] = {}
    for item in result.checks:
        grouped.setdefault(item.code, []).append(item)
    for code, items in grouped.items():
        if code == "lite_layout":
            lines.append(f"files: {items[0].message} (re-run bootstrap without --lite to upgrade)")
            continue
        for item in items:
            location = f" {item.path}:" if item.path else ""
            lines.append(f"check[{item.level}] {code}{location} {item.message}")
    if result.exit_code:
        # Count what actually blocked the run, so the summary never
        # contradicts the exit code (strict also blocks on warnings).
        blocking = blocking_levels(result.level)
        items = sum(item.level in blocking for item in result.checks) + len(result.errors)
        noun = "blocking item" if result.level == "strict" else "issue"
        lines.append(f"result: {items} {noun}(s) found")
    else:
        lines.append("result: healthy")
    return "\n".join(lines)


def check(project_dir: Path, *, level: str = "standard") -> int:
    """Report doc health without creating or modifying anything."""
    result = check_result(project_dir, level=level)
    print(render_check(result))
    return result.exit_code


REPORT_TEMPLATE = Path(__file__).resolve().parent.parent / "assets" / "report-template.html"
REPORT_DIR = "docs/reports"


def slugify(text: str) -> str:
    # Keep letters and digits from the user's locale so Chinese report names
    # remain distinct instead of collapsing to the generic "report" slug.
    slug = "".join(c.lower() if c.isalnum() else "-" for c in text)
    while "--" in slug:
        slug = slug.replace("--", "-")
    return slug.strip("-") or "report"


def prepare_target_error(project_dir: Path) -> str:
    """Return a dry-run-safe target path error without creating anything."""
    current = project_dir
    while not os.path.lexists(current):
        parent = current.parent
        if parent == current:
            break
        current = parent
    if os.path.lexists(current) and (current.is_symlink() or not current.is_dir()):
        return f"target parent is not a regular directory: {current}"
    return ""


def report_plan(project_dir: Path, *, slug: str, dry_run: bool = False) -> ReportResult:
    target = str(project_dir)
    normalized_slug = slugify(slug)
    result = ReportResult("report", target, normalized_slug, dry_run=dry_run)
    target_error = prepare_target_error(project_dir)
    if target_error:
        result.errors.append(target_error)
        result.exit_code = 1
        return result
    if project_dir.exists() and (project_dir.is_symlink() or not project_dir.is_dir()):
        result.errors.append("target is not a regular directory")
        result.exit_code = 1
        return result
    out_dir = project_dir / REPORT_DIR
    for ancestor in (project_dir / "docs", out_dir):
        if os.path.lexists(ancestor) and (ancestor.is_symlink() or not ancestor.is_dir()):
            rel = ancestor.relative_to(project_dir).as_posix()
            result.conflicts.append(rel)
            result.errors.append(f"report directory conflicts with a non-directory path: {rel}")
            result.exit_code = 1
            return result
    out = out_dir / f"{date.today().isoformat()}-{normalized_slug}.html"
    rel = out.relative_to(project_dir).as_posix()
    if os.path.lexists(out):
        if out.is_symlink() or not out.is_file():
            result.conflicts.append(rel)
            result.errors.append(f"report path conflicts with a non-regular file: {rel}")
            result.exit_code = 1
        else:
            result.skipped.append(rel)
        return result
    result.created.append(rel)
    return result


def write_report_result(project_dir: Path, *, slug: str, kind: str = "报告", dry_run: bool = False) -> ReportResult:
    """Create a report or return the side-effect-free report plan."""
    result = report_plan(project_dir, slug=slug, dry_run=dry_run)
    if result.errors or dry_run or result.skipped:
        return result

    try:
        project_dir.mkdir(parents=True, exist_ok=True)
        project_dir = project_dir.resolve()
        result.target = str(project_dir)
    except OSError as exc:
        result.created.clear()
        result.errors.append(f"unable to prepare target directory: {exc}")
        result.exit_code = 1
        return result

    try:
        if REPORT_TEMPLATE.is_symlink() or not REPORT_TEMPLATE.is_file():
            raise OSError(f"template missing or not a regular file at {REPORT_TEMPLATE}")
        template = REPORT_TEMPLATE.read_text(encoding="utf-8")
    except OSError as exc:
        result.created.clear()
        result.errors.append(f"unable to read report template: {exc}")
        result.exit_code = 1
        return result

    out_dir = project_dir / REPORT_DIR
    try:
        out_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        result.created.clear()
        result.errors.append(f"unable to prepare report directory: {exc}")
        result.exit_code = 1
        return result

    out = out_dir / f"{date.today().isoformat()}-{result.slug}.html"
    project_name = html.escape(project_title(project_dir), quote=True)
    report_title = html.escape(result.slug.replace("-", " "), quote=True)
    report_kind = html.escape(kind, quote=True)
    report_date = html.escape(date.today().isoformat(), quote=True)
    html_text = template
    for token, value in (
        ("{{TITLE}}", report_title),
        ("{{DATE}}", report_date),
        ("{{KIND}}", report_kind),
        ("{{PROJECT}}", project_name),
    ):
        html_text = html_text.replace(token, value)
    if any(token in html_text for token in ("{{TITLE}}", "{{DATE}}", "{{KIND}}", "{{PROJECT}}")):
        result.created.clear()
        result.errors.append("report template contains unresolved replacement tokens")
        result.exit_code = 1
        return result
    try:
        with out.open("x", encoding="utf-8", newline="\n") as handle:
            handle.write(html_text)
    except FileExistsError:
        rel = out.relative_to(project_dir).as_posix()
        result.created.clear()
        if out.is_symlink() or not out.is_file():
            result.conflicts.append(rel)
            result.errors.append("report path conflicts with a non-regular file")
            result.exit_code = 1
        else:
            result.skipped.append(rel)
    except OSError as exc:
        result.created.clear()
        result.errors.append(f"unable to write report {out.relative_to(project_dir).as_posix()}: {exc}")
        result.exit_code = 1
    return result


def render_report(result: ReportResult) -> str:
    lines = [f"target: {result.target}", "mode: report"]
    for error in result.errors:
        lines.append(f"error: {error}")
    lines.append("created: " + (", ".join(result.created) if result.created else "none"))
    lines.append("skipped: " + (", ".join(result.skipped) if result.skipped else "none"))
    lines.append("conflicts: " + (", ".join(result.conflicts) if result.conflicts else "none"))
    if result.created and not result.dry_run:
        lines.append("next: replace every 待补充, set a concise and specific <title>, drop unused sections")
        lines.append("warn: never write passwords/keys/tokens into a report - HTML is easy to forward")
    return "\n".join(lines)


def write_report(project_dir: Path, *, slug: str, kind: str = "报告") -> int:
    result = write_report_result(project_dir, slug=slug, kind=kind)
    print(render_report(result))
    return result.exit_code


def bootstrap_plan(project_dir: Path, *, mode: str = "minimal", commit: bool = False, dry_run: bool = False) -> BootstrapResult:
    target = str(project_dir)
    result = BootstrapResult("bootstrap", target, mode, dry_run=dry_run)
    target_error = prepare_target_error(project_dir)
    if target_error:
        result.errors.append(target_error)
        result.exit_code = 1
        return result
    if project_dir.exists() and (project_dir.is_symlink() or not project_dir.is_dir()):
        result.errors.append("target is not a regular directory")
        result.exit_code = 1
        return result

    try:
        if has_git_repository(project_dir):
            result.git = "skipped: .git already exists"
        else:
            result.git = "would-init: git repository" if dry_run else ""
    except (OSError, RuntimeError) as exc:
        result.git = f"failed: {exc}"

    for name in templates(project_dir, mode):
        path = project_dir / name
        if os.path.lexists(path):
            if path.is_file() and not path.is_symlink():
                result.skipped.append(name)
            else:
                result.conflicts.append(name)
        else:
            result.created.append(name)
    if commit:
        result.commit = "would-commit: generated files" if dry_run else ""
    else:
        result.commit = "not requested"
    # Doc-file conflicts and a bad .git do not abort the real run: the
    # remaining files are still created (write_missing_files reports
    # per-file conflicts; init_git failure continues with docs). Only
    # target-level errors block execution, so they stay out of errors here.
    result.exit_code = 1 if (result.errors or result.conflicts or result.git.startswith("failed")) else 0
    return result


def bootstrap_result(project_dir: Path, *, mode: str = "minimal", commit: bool = False, dry_run: bool = False) -> BootstrapResult:
    """Create starter files or return the side-effect-free bootstrap plan."""
    result = bootstrap_plan(project_dir, mode=mode, commit=commit, dry_run=dry_run)
    if result.errors or dry_run:
        return result
    try:
        project_dir.mkdir(parents=True, exist_ok=True)
        project_dir = project_dir.resolve()
        result.target = str(project_dir)
    except OSError as exc:
        result.errors.append(f"unable to prepare target directory: {exc}")
        result.exit_code = 1
        return result

    git_failed = False
    try:
        result.git = init_git(project_dir)
    except (OSError, RuntimeError) as exc:
        git_failed = True
        result.git = f"failed: {exc} - continuing with docs"
        result.errors.append(str(exc))
    try:
        result.created, result.skipped, result.conflicts = write_missing_files(project_dir, mode=mode)
    except OSError as exc:
        result.errors.append(f"unable to inspect or create project files: {exc}")
        result.exit_code = 1
        return result
    if commit and git_failed:
        result.commit = "skipped: git unavailable"
        result.errors.append("commit requested but git is unavailable")
    elif commit:
        commit_ok, result.commit = make_initial_commit(project_dir, result.created)
        if not commit_ok:
            result.errors.append(result.commit)
    result.exit_code = 1 if result.errors or result.conflicts else 0
    return result


def render_bootstrap(result: BootstrapResult) -> str:
    lines = [f"target: {result.target}", f"mode: {result.mode}"]
    if result.git:
        lines.append(f"git: {result.git}")
    lines.append("created: " + (", ".join(result.created) if result.created else "none"))
    lines.append("skipped: " + (", ".join(result.skipped) if result.skipped else "none"))
    lines.append("conflicts: " + (", ".join(result.conflicts) if result.conflicts else "none"))
    for error in result.errors:
        lines.append(f"error: {error}")
    if result.commit:
        lines.append(f"commit: {result.commit}")
    return "\n".join(lines)


def bootstrap(project_dir: Path, *, mode: str = "minimal", commit: bool = False) -> int:
    result = bootstrap_result(project_dir, mode=mode, commit=commit)
    print(render_bootstrap(result))
    return result.exit_code


class ResultArgumentParser(argparse.ArgumentParser):
    def error(self, message: str) -> None:
        if "--json" in sys.argv[1:]:
            payload = {
                "operation": "arguments",
                "target": str(Path.cwd()),
                "mode": "",
                "created": [],
                "skipped": [],
                "conflicts": [],
                "git": "",
                "commit": "",
                "report": "",
                "checks": [],
                "errors": [message],
                "exit_code": 2,
                "dry_run": "--dry-run" in sys.argv[1:],
            }
            print(json.dumps(payload, ensure_ascii=False, sort_keys=False))
            raise SystemExit(2)
        super().error(message)


def parse_args() -> argparse.Namespace:
    parser = ResultArgumentParser(
        description="Initialize a project with git and starter docs, or health-check existing docs (--check)."
    )
    parser.add_argument(
        "target",
        nargs="?",
        default=".",
        help="Target project directory. Defaults to the current directory.",
    )
    mode_group = parser.add_mutually_exclusive_group()
    mode_group.add_argument(
        "--full",
        action="store_true",
        help="Create the more detailed template with extra usage rules and collaboration guidance.",
    )
    mode_group.add_argument(
        "--lite",
        action="store_true",
        help="Small-project mode: create only README.md and .gitignore.",
    )
    parser.add_argument(
        "--commit",
        action="store_true",
        help="Commit the generated files (serves as the initial commit for a fresh repo).",
    )
    parser.add_argument(
        "--report",
        metavar="SLUG",
        nargs="?",
        const="report",
        help="Scaffold a one-off HTML report. With a target use TARGET --report [SLUG]; for the current directory use --report=SLUG.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Health-check existing project docs instead of creating anything.",
    )
    parser.add_argument(
        "--check-level",
        choices=("basic", "standard", "strict"),
        default="standard",
        help="Check depth: basic, standard (default), or strict.",
    )
    parser.add_argument(
        "--stale-days",
        type=int,
        metavar="N",
        help="Maximum age of the last-tidy date with --check (default: 30 days; 0 disables the age limit).",
    )
    parser.add_argument(
        "--placeholder",
        action="append",
        default=[],
        metavar="TEXT",
        help="Additional case-sensitive literal placeholder to flag with --check; repeat for multiple values.",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Render exactly one JSON result object to stdout.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show the operation plan without filesystem or Git side effects.",
    )
    args = parser.parse_args()
    raw = sys.argv[1:]
    operation_flags = [args.check, args.report is not None]
    if sum(operation_flags) > 1:
        parser.error("--check and --report are mutually exclusive operations")
    if args.check and (args.full or args.lite or args.commit):
        parser.error("--full, --lite, and --commit are only valid for initialization")
    if args.report is not None and (args.full or args.lite or args.commit):
        parser.error("--full, --lite, and --commit are only valid for initialization")
    if not args.check and any(value == "--check-level" or value.startswith("--check-level=") for value in raw):
        parser.error("--check-level is only valid with --check")
    if args.stale_days is not None:
        if not args.check:
            parser.error("--stale-days is only valid with --check")
        if args.stale_days < 0:
            parser.error("--stale-days must be non-negative")
    if args.placeholder:
        if not args.check:
            parser.error("--placeholder is only valid with --check")
        if any(not value.strip() for value in args.placeholder):
            parser.error("--placeholder must not be blank")
    report_index = next((i for i, value in enumerate(raw) if value == "--report"), None)
    if report_index is not None:
        before_report = [value for value in raw[:report_index] if not value.startswith("-")]
        after_report = raw[report_index + 1] if report_index + 1 < len(raw) else None
        if not before_report and after_report and not after_report.startswith("-"):
            parser.error("ambiguous report syntax: use --report=SLUG for the current directory, or TARGET --report [SLUG]")
    return args


def main() -> int:
    # Piped stdout on Chinese Windows defaults to GBK, which garbles doc
    # content echoed in reports; force UTF-8 so captured output stays readable.
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except (AttributeError, OSError):
            pass
    try:
        args = parse_args()
        target = Path(args.target)
        if args.check:
            result = check_result(
                target, level=args.check_level, dry_run=args.dry_run,
                stale_days=STALE_DAYS if args.stale_days is None else args.stale_days,
                extra_placeholders=tuple(args.placeholder),
            )
            if args.json:
                print(json.dumps(result.as_dict(), ensure_ascii=False, sort_keys=False))
            else:
                print(render_check(result))
            return result.exit_code
        if args.report is not None:
            result = write_report_result(target, slug=args.report, dry_run=args.dry_run)
            if args.json:
                print(json.dumps(result.as_dict(), ensure_ascii=False, sort_keys=False))
            else:
                print(render_report(result))
            return result.exit_code
        mode = "full" if args.full else ("lite" if args.lite else "minimal")
        result = bootstrap_result(target, mode=mode, commit=args.commit, dry_run=args.dry_run)
        if args.json:
            print(json.dumps(result.as_dict(), ensure_ascii=False, sort_keys=False))
        else:
            print(render_bootstrap(result))
        return result.exit_code
    except (OSError, RuntimeError, UnicodeError) as exc:
        if "--json" in sys.argv[1:]:
            payload = {
                "operation": "error",
                "target": str(Path.cwd()),
                "mode": "",
                "created": [],
                "skipped": [],
                "conflicts": [],
                "git": "",
                "commit": "",
                "report": "",
                "checks": [],
                "errors": [str(exc)],
                "exit_code": 1,
                "dry_run": "--dry-run" in sys.argv[1:],
            }
            print(json.dumps(payload, ensure_ascii=False, sort_keys=False))
        else:
            print(f"error: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
