# Repository-local variables exported by Git (see rev-parse --local-env-vars),
# plus the namespace override. A parent Git process must not redirect this
# tool's repository, index, object store, or per-invocation configuration.
GIT_LOCAL_ENV = frozenset({
    "GIT_ALTERNATE_OBJECT_DIRECTORIES", "GIT_CONFIG", "GIT_CONFIG_PARAMETERS",
    "GIT_CONFIG_COUNT", "GIT_OBJECT_DIRECTORY", "GIT_DIR", "GIT_WORK_TREE",
    "GIT_IMPLICIT_WORK_TREE", "GIT_GRAFT_FILE", "GIT_INDEX_FILE",
    "GIT_NO_REPLACE_OBJECTS", "GIT_REPLACE_REF_BASE", "GIT_PREFIX",
    "GIT_SHALLOW_FILE", "GIT_COMMON_DIR", "GIT_NAMESPACE",
})


def run_git(project_dir: Path, *args: str, read_only: bool = False) -> subprocess.CompletedProcess[str]:
    """Run Git against the target's .git entry with repository-local isolation."""
    # Preserve normal author/committer settings and user/system configuration.
    environment = {
        key: value for key, value in os.environ.items()
        if key not in GIT_LOCAL_ENV
        and not key.startswith(("GIT_CONFIG_KEY_", "GIT_CONFIG_VALUE_"))
    }
    if read_only:
        environment["GIT_OPTIONAL_LOCKS"] = "0"
    return subprocess.run(
        ["git", "--git-dir=.git", *args],
        cwd=project_dir,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
        env=environment,
    )


def read_git(project_dir: Path, *args: str) -> subprocess.CompletedProcess[str]:
    """Read the target repository without refreshing its index or taking locks."""
    return run_git(project_dir, *args, read_only=True)


def has_git_repository(project_dir: Path) -> bool:
    """Accept a local repository or gitfile; reject invalid .git paths.

    An explicit git directory prevents a malformed .git from falling back to
    a parent repository. Git resolves worktree and submodule gitfiles itself.
    """
    git_path = project_dir / ".git"
    if not os.path.lexists(git_path):
        return False
    if git_path.is_symlink() or not (git_path.is_dir() or git_path.is_file()):
        raise RuntimeError(f"{git_path} is not a regular Git directory or gitfile")
    repository = read_git(project_dir, "rev-parse", "--show-toplevel")
    if repository.returncode != 0:
        message = (repository.stderr or repository.stdout or "repository probe failed").strip()
        raise RuntimeError(f"invalid Git repository at {git_path}: {message}")
    top_level = repository.stdout.rstrip("\r\n")
    if not top_level or not Path(top_level).samefile(project_dir):
        raise RuntimeError(f"Git repository root does not match {project_dir}")
    return True


def init_git(project_dir: Path) -> str:
    if has_git_repository(project_dir):
        return "skipped: .git already exists"

    result = run_git(project_dir, "init")
    if result.returncode != 0:
        message = (result.stderr or result.stdout or "git init failed").strip()
        raise RuntimeError(message)
    if not has_git_repository(project_dir):
        raise RuntimeError(f"git init did not create a repository at {project_dir}")
    return "created: git repository initialized"


def make_initial_commit(project_dir: Path, files: list[str]) -> tuple[bool, str]:
    """Commit only files created by this run and report whether it succeeded."""
    if not files:
        return True, "skipped: nothing new to commit"
    try:
        add = run_git(project_dir, "add", "--", *files)
        if add.returncode != 0:
            message = (add.stderr or add.stdout or "git add failed").strip()
            return False, f"failed: git add: {message}"
        # Pathspec limits the commit to these files, so anything the user had
        # staged beforehand stays staged and uncommitted.
        commit = run_git(project_dir, "commit", "-m", "chore: bootstrap project docs", "--", *files)
    except OSError as exc:
        return False, f"failed: git not available: {exc}"
    if commit.returncode != 0:
        message = (commit.stderr or commit.stdout or "git commit failed").strip()
        return False, f"failed: {message}"
    return True, "created: committed generated files"


def write_missing_files(
    project_dir: Path, *, mode: str
) -> tuple[list[str], list[str], list[str]]:
    created: list[str] = []
    skipped: list[str] = []
    conflicts: list[str] = []
    for name, content in templates(project_dir, mode).items():
        path = project_dir / name
        if os.path.lexists(path):
            if path.is_file() and not path.is_symlink():
                skipped.append(name)
            else:
                conflicts.append(name)
            continue
        try:
            # Exclusive creation preserves the no-overwrite guarantee even if
            # another process creates the path after the existence check.
            with path.open("x", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
            created.append(name)
        except FileExistsError:
            # Reclassify a path created concurrently instead of overwriting it.
            if path.is_file() and not path.is_symlink():
                skipped.append(name)
            else:
                conflicts.append(name)
        except OSError as exc:
            conflicts.append(f"{name} ({exc})")
    return created, skipped, conflicts


